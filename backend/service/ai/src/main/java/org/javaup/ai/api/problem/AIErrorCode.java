package org.javaup.ai.api.problem;

/**
 * ai-service 对外响应和持久化失败记录使用的稳定错误码。
 * HTTP 状态与具体说明由调用位置提供；同一错误码可出现在不同业务上下文中。
 */
public enum AIErrorCode {
    // 请求格式与参数校验。
    VALIDATION_FAILED,
    INVALID_PARAMETER_TYPE,
    MALFORMED_REQUEST,
    MISSING_REQUEST_VALUE,

    // 分析任务、版本、状态与执行预算。
    INVALID_SESSION_REQUEST,
    INVALID_SESSION_SOURCE,
    INVALID_SESSION_CONFIGURATION,
    INVALID_SESSION_ID,
    INVALID_ASSESSMENT_ID,
    ACTIVE_SESSION_EXISTS,
    ACTIVE_SESSION_NOT_FOUND,
    AGENT_SESSION_NOT_FOUND,
    SESSION_NOT_READY,
    SESSION_NOT_RESUMABLE,
    SESSION_FINISHED,
    EXECUTION_STILL_RUNNING,
    EXPECTED_VERSION_REQUIRED,
    SESSION_VERSION_CONFLICT,
    IDEMPOTENCY_KEY_REUSED,
    MODEL_BUDGET_EXHAUSTED,
    STEP_BUDGET_EXHAUSTED,
    AI_DAILY_QUOTA_EXCEEDED,
    PAYMENT_ENTITLEMENT_UNAVAILABLE,

    // 问答、检查点与结果。
    INVALID_AGENT_ANSWER,
    INVALID_REVISION,
    NOT_WAITING_FOR_ANSWER,
    ANSWER_REQUIRED,
    ANSWER_TYPE_MISMATCH,
    ANSWER_STEP_NOT_FOUND,
    ANSWER_BASE_MISSING,
    QUESTION_CHANGED,
    QUESTION_MISSING,
    CHECKPOINT_CHANGED,
    CHECKPOINT_NOT_FOUND,
    CHECKPOINT_CORRUPTED,
    STATE_SCHEMA_UNSUPPORTED,
    INVALID_STEP_PATH,
    OUTCOME_NOT_READY,

    // 模型配置、请求与输出。
    INVALID_MODEL_SELECTION,
    MODEL_SELECTION_REQUIRED,
    MODEL_NOT_ALLOWED,
    MODEL_NOT_CONFIGURED,
    MODEL_CONTEXT_TOO_LARGE,
    MODEL_CALL_FAILED,
    INVALID_MODEL_OUTPUT,
    TOO_MANY_MODEL_PICTURES,
    MODEL_IMAGE_HOST_NOT_ALLOWED,
    MODEL_IMAGE_TYPE_NOT_ALLOWED,
    MODEL_IMAGE_TOO_LARGE,
    MODEL_IMAGE_UNAVAILABLE,

    // 有界的最终结果评审与纠正。
    QUALITY_REVIEW_NOT_CONFIGURED,
    QUALITY_REVIEW_CALL_FAILED,
    INVALID_QUALITY_REVIEW_OUTPUT,
    INVALID_REVIEW_CANDIDATE,
    INVALID_MODEL_REVISION,
    MODEL_REVISION_NOT_SUPPORTED,

    // History / Image 服务协作。
    ASSESSMENT_INPUT_UNAVAILABLE,
    INVALID_ASSESSMENT_INPUT,
    ASSESSMENT_ANNOTATION_CHANGED,
    ASSESSMENT_PICTURES_UNAVAILABLE,
    INVALID_PICTURE_SNAPSHOT,
    RESULT_FINALIZATION_UNAVAILABLE,
    INVALID_FINALIZATION_RESPONSE;

    /** 枚举名称就是现有接口错误码；重命名时必须考虑契约兼容性。 */
    public String code() {
        return name();
    }
}
